const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const elements = new Map();
const document = {getElementById(id) {
  if (!elements.has(id)) elements.set(id, {textContent:'', scrollTop:0, scrollHeight:0, setAttribute(){}});
  return elements.get(id);
}};
let copied;
const window = {AndroidNav:{action(kind,json){copied={kind,...JSON.parse(json)};}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../assets/gps-monitor.js'),'utf8'), {window,document,Date,JSON});
const get = id => document.getElementById(id);
const state = {connected:true,vehicleLive:true,gpsDiagnosticsLive:true,vehicle:{valid:false,uart:true,satellites:0,age:4294967,hdop:null},gpsDiagnostics:{supported:true,time:1,chars:70000,passed:100,failed:2,fixSentences:0}};
window.GPSMonitor.update({connected:false});
assert.match(get('gpsMonitorStatus').textContent,/未连接/);
window.GPSMonitor.update({connected:true,gpsDiagnostics:{supported:false}});
assert.match(get('gpsMonitorStatus').textContent,/烧录新版/);
window.GPSMonitor.update(state);
assert.match(get('gpsMonitorLatest').textContent,/UART=70000/);
assert.match(get('gpsMonitorLatest').textContent,/无有效位置/);
const history=get('gpsMonitorHistory').textContent;
window.GPSMonitor.update(state);
assert.equal(get('gpsMonitorHistory').textContent,history);
get('gpsMonitorPause').onclick();
window.GPSMonitor.update({...state,gpsDiagnostics:{...state.gpsDiagnostics,time:2}});
assert.equal(get('gpsMonitorHistory').textContent,history);
get('gpsMonitorPause').onclick();
for(let time=3;time<60;time++)window.GPSMonitor.update({...state,gpsDiagnostics:{...state.gpsDiagnostics,time}});
assert.equal(get('gpsMonitorHistory').textContent.split('\n').length,40);
window.GPSMonitor.update({...state,connected:false,vehicleLive:false,gpsDiagnosticsLive:false});
assert.match(get('gpsMonitorLatest').textContent,/上次记录/);
assert.match(get('gpsMonitorLatest').textContent,/VALID=—/);
get('gpsMonitorCopy').onclick();
assert.equal(copied.kind,'copyGpsLog');
assert.ok(copied.text.length<=6000);
get('gpsMonitorClear').onclick();
assert.equal(get('gpsMonitorHistory').textContent,'暂无记录');
console.log('GPS monitor scenarios passed: waiting, legacy firmware, counters, stale data, pause, bounded history, copy, clear');
